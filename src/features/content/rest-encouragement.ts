/**
 * 이번 쉬는 시간에 보여줄 문구.
 *
 * 같은 세트에서는 계속 같은 문구가 보여야 한다 — 1초마다 바뀌면 읽다가 놓치고
 * 화면이 산만해진다. 그래서 seed(보통 세트 번호)로 고르고, 초 단위 타이머와는
 * 분리한다.
 *
 * 연령대를 모르면 공통 문구만 쓴다. 모르는 상태에서 "40대부터는..."을 띄우면
 * 20대에게는 엉뚱한 말이 된다.
 */
export function pickRestMessage(ageGroup: AgeGroup | undefined, seed: number): RestMessage {
  const pool = ageGroup ? [...COMMON, ...BY_AGE[ageGroup]] : COMMON;
  return pool[Math.abs(Math.trunc(seed)) % pool.length];
}
