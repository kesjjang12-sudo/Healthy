/**
 * 문자열을 정수로. 운동마다 다른 문구가 나오게 하는 데만 쓴다.
 * 암호학적 성질은 필요 없고, 같은 입력에 같은 값만 나오면 된다.
 */
function hashString(value: string): number {
  let hash = 0;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) | 0;
  }
  return Math.abs(hash);
}

/**
 * 이번 쉬는 시간에 보여줄 문구.
 *
 * seed 를 세트 번호만으로 잡으면 안 된다. 세트는 보통 2~3 이라 문구를 20개
 * 넣어도 2·3번만 평생 나온다. 그래서 운동(routineId)까지 섞어서, 같은 날
 * 운동을 옮길 때마다 다른 문구가 나오게 한다.
 *
 * 반대로 같은 운동의 같은 세트에서는 계속 같은 문구여야 한다 — 1초마다 바뀌면
 * 읽다가 놓치고 화면만 산만해진다. 그래서 남은 초는 seed 에 넣지 않는다.
 *
 * 연령대를 모르면 공통 문구만 쓴다. 모르는 상태에서 "40대부터는..."을 띄우면
 * 20대에게는 엉뚱한 말이 된다.
 */
export function pickRestMessage(
  ageGroup: AgeGroup | undefined,
  routineId: string,
  setNumber: number,
): RestMessage {
  const pool = ageGroup ? [...BY_AGE[ageGroup], ...COMMON] : COMMON;
  const seed = hashString(routineId) + setNumber;
  return pool[seed % pool.length];
}
