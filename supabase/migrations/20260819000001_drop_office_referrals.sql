-- 기구 주의사항에서 "관리사무소에 알리세요"를 걷어낸다.
--
-- 아픈 곳을 말씀하신 분께 "관리사무소에 문의하세요"라고 돌려보내면, 정작
-- 아픈 곳을 반영해 무게를 낮추고 위험한 동작을 빼 주는 일을 우리가 이미
-- 하고 있다는 게 안 보인다. 앱이 도와주지 못한다는 인상만 남는다.
-- 그래서 안내는 "멈추고 쉬세요"까지만 하고, 그 뒤는 앱이 알아서 한다.
--
-- 20260814000029_how_to_steps 가 넣은 두 줄만 손본다. 이름으로 찾되,
-- 실제로 그 문구가 남아 있을 때만 바꾼다(다른 세션이 이미 고쳤을 수 있다).

update public.exercise_catalog
set form_caution = '무릎 앞쪽이 아프면 즉시 멈추고 쉬세요. 반동으로 차 올리지 마세요.'
where name_ko = '앉아서 무릎 펴기'
  and form_caution like '%관리사무소%';

update public.exercise_catalog
set form_caution = '일직선을 넘어 허리를 뒤로 젖히지 마세요. 허리가 아프면 이 동작은 건너뛰세요.'
where name_ko = '엎드려 허리 젖히기'
  and form_caution like '%관리사무소%';
